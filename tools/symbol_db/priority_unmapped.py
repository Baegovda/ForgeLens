#!/usr/bin/env python3
"""Build docs/SYMBOL_DB/PRIORITY_UNMAPPED.md: asset-relevant functions NOT yet in the symbol DB, ranked.

Input: docs/SYMBOL_DB/rea_string_xrefs.tsv (function | domains | in_symbol_db | string_count | strings).
No new RE: pure re-ranking of existing REA string-xref data.

Filter (HEURISTIC): drops ECS/registration boilerplate and generic strings:
  - every string is an ECS/registration name (ecgsCOMPONENT_*, ecs*, sslOBJ<..>, hk*/hknp* class names,
    CB_/RB_ layout-only names are kept), a source path (C:\\..., *.cpp), or a generic word (<= 1 token, common)
Score (HEURISTIC weights):
  domain weight (physics/meshes x1.5 = low coverage) + open-item keyword bonus (BOT_TRANSFER §7)
  + specificity (distinct non-generic strings, camelCase/param-like names) + log2(1+string_count).
Usage: priority_unmapped.py [repo_root]
"""
import math, os, re, sys
from collections import defaultdict

root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = os.path.join(root, "docs/SYMBOL_DB/rea_string_xrefs.tsv")
out = os.path.join(root, "docs/SYMBOL_DB/PRIORITY_UNMAPPED.md")
TOP = 25

DOMAIN_W = {"physics": 1.5, "meshes": 1.5, "vfx": 1.2, "animation": 1.2, "customization": 1.2,
            "materials": 1.0, "rendering": 1.0, "shaders": 0.8, "containers": 0.8}
# open items (BOT_TRANSFER.md §7) -> keyword regex
OPEN = [
    ("§7.1 trail / vfx", r"trail|ribbon|trlPOINT|emitter|particle|sfx", 3.0),
    ("§7.2 adaptive light", r"adapt|avgLum|exposure|lumin|eyeAdapt", 3.0),
    ("§7.4 fire clip / anim", r"shoot|fire|muzzle|recoil|aim|morpheme|anim_?graph|reload", 3.0),
    ("§7.6 pauldron colours", r"pauldron|shoulder|colou?r_?scheme|gauntlet|greave|tint", 2.5),
    ("§7.10/11 physics / cloth", r"cloth|jiggle|spring|damp|ragdoll|constraint", 2.5),
    ("§7.12 level / prop placement", r"cd_list|class_list|placing|placement|spawn|prop|level|scene|instance", 2.5),
]
OPEN = [(n, re.compile(p, re.I), w) for n, p, w in OPEN]
BOILER = re.compile(r"^(ecgs?COMPONENT_|ecs|sslOBJ<|hk[a-zA-Z]+$|hknp|C:\\|.*\.(cpp|h)$|TtSCS::|Format\\)", re.I)
GENERIC = {"animation", "material", "mesh", "physics", "shader", "render", ".resource", "resource", "model",
           "name", "type", "data", "default", "none", "color", "texture", "tint: "}

def is_generic(s):
    s2 = s.strip()
    return s2.lower() in GENERIC or len(s2) < 4 or (re.fullmatch(r"[a-z]+", s2) is not None and len(s2) < 8)

rows, unmapped = [], 0
for i, line in enumerate(open(src, encoding="utf-8")):
    if i == 0: continue
    f = line.rstrip("\n").split("\t")
    if len(f) < 5 or f[2].strip(): continue
    unmapped += 1
    strs = [s.strip() for s in f[4].split(" | ") if s.strip()]
    useful = [s for s in strs if not BOILER.match(s) and not is_generic(s)]
    if not useful: continue
    doms = [d for d in f[1].split(",") if d]
    dw = max(DOMAIN_W.get(d, 1.0) for d in doms) if doms else 1.0
    text = " ".join(useful)
    hits = [(n, w) for n, rx, w in OPEN if rx.search(text)]
    spec = sum(1.0 + (0.5 if re.search(r"[a-z][A-Z]|_", s) else 0) for s in useful[:8])
    score = dw * (spec + math.log2(1 + int(f[3] or 0))) + sum(w for _, w in hits)
    key = sorted(useful, key=lambda s: -len(s))[:4]
    rows.append(dict(addr=f[0], doms=doms, score=score, key=key, items=[n for n, _ in hits]))

by = defaultdict(list)
for r in rows:
    for d in r["doms"]: by[d].append(r)

L = ["# Priority table: asset-relevant functions not yet in the symbol DB", "",
     f"Generated by `tools/symbol_db/priority_unmapped.py` from `rea_string_xrefs.tsv` (no new RE). Regenerate after the TSV changes.", "",
     f"- Unmapped functions (in_symbol_db empty): **{unmapped}**",
     f"- After boilerplate filter: **{len(rows)}**", "",
     "**HEURISTIC filter:** functions whose strings are all ECS/registration names (`ecgsCOMPONENT_*`, `sslOBJ<…>`, bare Havok class names),",
     "source paths, or generic words are dropped. This may drop real functions; check the TSV if a lead is missing.", "",
     "**HEURISTIC score:** domain weight (physics/meshes ×1.5 low coverage; vfx/animation/customization ×1.2) × (string specificity + log2(1+string_count))",
     "+ bonus for keywords of open items (BOT_TRANSFER §7). The ranking is a lookup aid only, not evidence; nothing here is PROVEN.", ""]
for d in sorted(by, key=lambda d: -DOMAIN_W.get(d, 1)):
    lst = sorted(by[d], key=lambda r: -r["score"])[:TOP]
    L += [f"## {d} ({len(by[d])} candidates, top {len(lst)})", "", "| address | domain(s) | score | key strings | suggested open item |", "|---|---|---|---|---|"]
    for r in lst:
        ks = " · ".join(f"`{k.replace('|','/').replace('`','')[:50]}`" for k in r["key"])
        L.append(f"| {r['addr']} | {','.join(r['doms'])} | {r['score']:.1f} | {ks} | {'; '.join(r['items']) or '-'} |")
    L.append("")
open(out, "w", encoding="utf-8").write("\n".join(L))
print(f"unmapped={unmapped} after_filter={len(rows)}")
for d in sorted(by):
    print(d, [(r["addr"], round(r["score"], 1), r["key"][:2]) for r in sorted(by[d], key=lambda r: -r["score"])[:5]])
